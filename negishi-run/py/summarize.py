def say(s=""):
    L.append(s)


def read_tsv(p, comment="#"):
    p = pathlib.Path(p)
    if not p.exists():
        return []
    rows = [l for l in p.read_text(errors="replace").splitlines() if l and not l.startswith(comment)]
    if not rows:
        return []
    hdr = rows[0].split("\t")
    return [dict(zip(hdr, r.split("\t"))) for r in rows[1:]]


def write_tsv(name, rows, cols):
    with open(str(TAB / name), "w") as fh:
        fh.write("\t".join(cols) + "\n")
        for r in rows:
            fh.write("\t".join(str(r.get(c, "")) for c in cols) + "\n")


def md_table(rows, cols, heads=None):
    say("| " + " | ".join(heads or cols) + " |")
    say("|" + "---|" * len(cols))
    for r in rows:
        say("| " + " | ".join(str(r.get(c, "")).replace("|", "/").replace("\n", " ") for c in cols) + " |")
    say()


